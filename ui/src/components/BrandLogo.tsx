import { useId } from "react";

import { cn } from "@/lib/utils";

/**
 * NIMBORA logo. The mark — an open orbit (the "nimbus") around a voice
 * waveform, with a satellite dot for the AI agent — is inline SVG so its bars
 * can breathe (`animated`, on by default; respects prefers-reduced-motion).
 *
 * - default: mark + wordmark, theme-aware (ink text on light, white on dark)
 * - `inverse`: force the white wordmark (always-dark surfaces)
 * - `mark`: the mark alone (sidebar, avatars)
 * Height comes from the caller (e.g. "h-7"); width follows the aspect ratio.
 * Static files for other uses live in /public/brand (generated by
 * ui/scripts/brand/generate_brand.py).
 */
const BARS = [
  { x: 16.8, h: 10 },
  { x: 23.3, h: 22 },
  { x: 29.8, h: 30 },
  { x: 36.3, h: 20 },
  { x: 42.8, h: 11 },
];

export function BrandMark({
  className,
  animated = true,
}: {
  className?: string;
  animated?: boolean;
}) {
  const id = useId().replace(/:/g, "");
  return (
    <svg
      viewBox="0 0 64 64"
      fill="none"
      role="img"
      aria-label="NIMBORA"
      className={cn("nimbora-mark shrink-0", animated && "nimbora-mark--live", className)}
    >
      <defs>
        <linearGradient id={`${id}-ring`} x1="8" y1="8" x2="56" y2="56" gradientUnits="userSpaceOnUse">
          <stop offset="0" stopColor="#22E5FF" />
          <stop offset="0.55" stopColor="#7C5CFF" />
          <stop offset="1" stopColor="#FF4FD8" />
        </linearGradient>
        <linearGradient id={`${id}-bars`} x1="32" y1="14" x2="32" y2="50" gradientUnits="userSpaceOnUse">
          <stop offset="0" stopColor="#22E5FF" />
          <stop offset="1" stopColor="#7C5CFF" />
        </linearGradient>
        <radialGradient id={`${id}-dot`} cx="0.5" cy="0.5" r="0.5">
          <stop offset="0" stopColor="#FFFFFF" />
          <stop offset="0.45" stopColor="#FF4FD8" />
          <stop offset="1" stopColor="#FF4FD8" stopOpacity="0" />
        </radialGradient>
      </defs>
      <g className="nimbora-mark__orbit">
        <path
          d="M43.74 9.93 A25 25 0 1 1 18.75 10.8"
          stroke={`url(#${id}-ring)`}
          strokeWidth="5"
          strokeLinecap="round"
        />
        <circle cx="36.34" cy="7.38" r="7" fill={`url(#${id}-dot)`} className="nimbora-mark__halo" />
        <circle cx="36.34" cy="7.38" r="3.2" fill="#FF4FD8" />
      </g>
      <g fill={`url(#${id}-bars)`}>
        {BARS.map((bar, i) => (
          <rect
            key={bar.x}
            x={bar.x}
            y={32 - bar.h / 2}
            width="4.4"
            height={bar.h}
            rx="2.2"
            className="nimbora-mark__bar"
            style={{ animationDelay: `${i * 0.14}s` }}
          />
        ))}
      </g>
    </svg>
  );
}

export function BrandLogo({
  className,
  inverse = false,
  mark = false,
  animated = true,
}: {
  className?: string;
  inverse?: boolean;
  mark?: boolean;
  animated?: boolean;
}) {
  if (mark) {
    return <BrandMark className={cn("w-auto select-none", className)} animated={animated} />;
  }
  // Full lockup: the wordmark is outlined Space Grotesk (static SVG, renders
  // identically everywhere); the theme picks ink-on-light or white-on-dark.
  /* eslint-disable @next/next/no-img-element */
  if (inverse) {
    return (
      <img src="/brand/nimbora-logo-on-dark.svg" alt="NIMBORA" className={cn("w-auto select-none", className)} />
    );
  }
  return (
    <>
      <img
        src="/brand/nimbora-logo-on-light.svg"
        alt="NIMBORA"
        className={cn("block w-auto select-none dark:hidden", className)}
      />
      <img
        src="/brand/nimbora-logo-on-dark.svg"
        alt="NIMBORA"
        className={cn("hidden w-auto select-none dark:block", className)}
      />
    </>
  );
  /* eslint-enable @next/next/no-img-element */
}
