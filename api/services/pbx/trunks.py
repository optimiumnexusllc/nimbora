@dataclass
class DialRule:
    pattern: str
    strip_digits: int = 0
    prefix: str = ""
    external_prefix: str = ""
    caller_id: str = ""

    def validate(self) -> None:
        self.pattern = self.pattern.strip()
        if not DIAL_PATTERN.match(self.pattern):
            raise PbxRouteError(
                f"Motif « {self.pattern} » invalide : chiffres, ou « _ » suivi de "
                "X (un chiffre), N (2-9), Z (1-9), [plage] et « . » (la suite).",
                422,
            )
        if not 0 <= self.strip_digits <= 20:
            raise PbxRouteError("Chiffres à retirer : entre 0 et 20", 422)
        for name, value in (
            ("préfixe", self.prefix),
            ("préfixe opérateur", self.external_prefix),
        ):
            if value and not re.fullmatch(r"[0-9*#+]{1,20}", value):
                raise PbxRouteError(f"{name.capitalize()} invalide", 422)
        if self.caller_id and not CALLER_ID.match(self.caller_id.replace(" ", "")):
            raise PbxRouteError("Numéro présenté invalide", 422)
        self.caller_id = self.caller_id.replace(" ", "")


@dataclass
class NewOutboundRoute:
    name: str
    trunk_ids: list[int]
    rules: list[DialRule] = field(default_factory=list)
    internal_caller_id: bool = False
    ring_seconds: int = 60

    def validate(self) -> None:
        self.name = self.name.strip()
        if not self.name:
            raise PbxRouteError("Nom de la route manquant", 422)
        if not self.trunk_ids:
            raise PbxRouteError("Choisissez au moins une ligne opérateur", 422)
        if len(set(self.trunk_ids)) != len(self.trunk_ids):
            raise PbxRouteError("Une ligne apparaît deux fois", 422)
        if not 1 <= len(self.rules) <= 20:
            raise PbxRouteError("Entre 1 et 20 motifs de numérotation", 422)
        for rule in self.rules:
            rule.validate()
        patterns = [r.pattern for r in self.rules]
        if len(set(patterns)) != len(patterns):
            raise PbxRouteError("Un motif apparaît deux fois", 422)


async def _outcall_context(client: PbxClient) -> str:
    contexts = await client.contexts("outcall")
    if not contexts:
        raise PbxRouteError(
            "Aucun contexte d'appels sortants sur le PBX : créez-en un (type "
            "« outcall ») et incluez-le dans le contexte interne.",
            409,
        )
    return contexts[0]["name"]


async def create_outbound_route(
    organization_id: int, spec: NewOutboundRoute, **client_kwargs
) -> dict:
    spec.validate()
    connection = await _connection(organization_id)
    async with client_for(connection, **client_kwargs) as client:
        known = {t.get("id") for t in await client.trunks()}
        missing = [t for t in spec.trunk_ids if t not in known]
        if missing:
            raise PbxRouteError("Ligne opérateur introuvable", 404)
        context = await _outcall_context(client)
        for rule in spec.rules:
            if await client.extensions(exten=rule.pattern, context=context):
                raise PbxRouteError(
                    f"Le motif {rule.pattern} est déjà utilisé par une autre route", 409
                )
        outcall = await client.create_outcall(
            {
                "name": spec.name[:128],
                "description": f"{brand().name}",
                "internal_caller_id": spec.internal_caller_id,
                "ring_time": max(10, min(spec.ring_seconds, 300)),
                "enabled": True,
            }
        )
        created: list[int] = []
        try:
            await client.set_outcall_trunks(outcall["id"], spec.trunk_ids)
            for rule in spec.rules:
                extension = await client.create_extension(rule.pattern, context)
                created.append(extension["id"])
                pattern: dict[str, Any] = {"strip_digits": rule.strip_digits}
                if rule.prefix:
                    pattern["prefix"] = rule.prefix
                if rule.external_prefix:
                    pattern["external_prefix"] = rule.external_prefix
                if rule.caller_id:
                    pattern["caller_id"] = rule.caller_id
                await client.associate_outcall_extension(
                    outcall["id"], extension["id"], pattern
                )
        except PbxError:
            await client.delete_outcall(outcall["id"])
            for extension_id in created:
                try:
                    await client.delete_extension(extension_id)
                except PbxError:
                    pass
            raise
    return {"id": outcall["id"], "name": spec.name}


async def list_outbound_routes(organization_id: int, **client_kwargs) -> list[dict]:
    connection = await _connection(organization_id)
    async with client_for(connection, **client_kwargs) as client:
        outcalls = await client.outcalls()
    return [
        {
            "id": o.get("id"),
            "name": o.get("name"),
            "enabled": o.get("enabled", True),
            "internal_caller_id": bool(o.get("internal_caller_id")),
            "trunks": [
                {
                    "id": t.get("id"),
                    "label": (t.get("endpoint_sip") or {}).get("label")
                    or (t.get("endpoint_sip") or {}).get("name")
                    or f"Ligne {t.get('id')}",
                }
                for t in o.get("trunks") or []
            ],
            "rules": [
                {
                    "pattern": e.get("exten"),
                    "strip_digits": e.get("strip_digits") or 0,
                    "prefix": e.get("prefix") or "",
                    "external_prefix": e.get("external_prefix") or "",
                    "caller_id": e.get("caller_id") or "",
                }
                for e in o.get("extensions") or []
            ],
        }
        for o in outcalls
    ]


async def delete_outbound_route(
    organization_id: int, outcall_id: int, **client_kwargs
) -> None:
    connection = await _connection(organization_id)
    async with client_for(connection, **client_kwargs) as client:
        outcalls = {o.get("id"): o for o in await client.outcalls()}
        outcall = outcalls.get(outcall_id)
        if outcall is None:
            raise PbxRouteError("Route introuvable", 404)
        await client.delete_outcall(outcall_id)
        for extension in outcall.get("extensions") or []:
            if extension.get("id"):
                try:
                    await client.delete_extension(extension["id"])
                except PbxError as error:
                    if error.status != 404:
                        raise


def dialled_number(rule: DialRule, dialled: str) -> str:
    """What the operator receives for ``dialled`` (for the editor's preview)."""
    number = (
        dialled[len(rule.prefix) :]
        if rule.prefix and dialled.startswith(rule.prefix)
        else dialled
    )
    return f"{rule.external_prefix}{number[rule.strip_digits :]}"


def pattern_matches(pattern: str, dialled: str) -> bool:
    """The PBX's dial pattern semantics, for the editor's live test."""
    if not pattern.startswith("_"):
        return pattern == dialled
    regex = ""
    body = pattern[1:]
    i = 0
    while i < len(body):
        char = body[i]
        if char in "Xx":
            regex += "[0-9]"
        elif char in "Nn":
            regex += "[2-9]"
        elif char in "Zz":
            regex += "[1-9]"
        elif char == ".":
            regex += ".+"
        elif char == "!":
            regex += ".*"
        elif char == "[":
            end = body.find("]", i)
            if end == -1:
                return False
            regex += f"[{re.escape(body[i + 1 : end]).replace(chr(92) + '-', '-')}]"
            i = end
        else:
            regex += re.escape(char)
        i += 1
    return re.fullmatch(regex, dialled) is not None
