"""Generate the shared Asterisk's contact-center configuration from the DB.

Three files are rendered for all tenants at once and included by the static
configuration shipped in ``deploy/asterisk``:

* ``pjsip_nimbora_agents.conf`` – one WebRTC endpoint/auth/aor per agent;
* ``queues_nimbora.conf`` – one queue per tenant queue with its members;
* ``extensions_nimbora.conf`` – explicit dialplan: the queue entry points the
  AI transfers into, and one context per tenant so agents can only call
  colleagues of their own company (no PSTN egress → no toll fraud).

Names embed the organization id (``t12-support``, ``t12_1001``) so tenants
never collide, and every value written is validated or sanitized because a
config-file injection would compromise the whole platform.
"""

from __future__ import annotations

import asyncio
import hashlib
import os
import re
import secrets
import tempfile
from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path

import aiohttp
from loguru import logger

from api.constants import (
    ASTERISK_ARI_PASSWORD,
    ASTERISK_ARI_URL,
    ASTERISK_ARI_USER,
    ASTERISK_GENERATED_CONFIG_DIR,
    ASTERISK_SIP_REALM,
    CONTACT_CENTER_ENABLED,
)
from api.db.models import ContactCenterAgentModel, ContactCenterQueueModel
from api.services.contact_center.destinations import (
    QUEUE_DIALPLAN_CONTEXT,
    queue_asterisk_name,
)
from api.services.contact_center.handoff import (
    CHANNEL_VARIABLE as HANDOFF_CHANNEL_VARIABLE,
)
from api.services.contact_center.handoff import (
    HEADER_NAME as HANDOFF_HEADER,
)

PJSIP_FILE = "pjsip_nimbora_agents.conf"
QUEUES_FILE = "queues_nimbora.conf"
EXTENSIONS_FILE = "extensions_nimbora.conf"

ALLOWED_STRATEGIES = {
    "ringall",
    "leastrecent",
    "fewestcalls",
    "random",
    "rrmemory",
    "linear",
    "wrandom",
}
EXTENSION_RE = re.compile(r"^[0-9]{2,6}$")
# Overflow targets: an E.164-ish number or a colleague extension.
OVERFLOW_NUMBER_RE = re.compile(r"^\+?[0-9]{2,15}$")
_SAFE_TEXT_RE = re.compile(r"[^\w \-\.'À-ÿ]", re.UNICODE)

HANDOFF_GOSUB_CONTEXT = "nimbora-handoff"
CALLBACK_DIALPLAN_CONTEXT = "nimbora-callback-out"

_reload_lock = asyncio.Lock()


@dataclass(frozen=True)
class AgentCredentials:
    sip_username: str
    password: str
    md5_cred: str


def agent_sip_username(organization_id: int, extension: str) -> str:
    return f"t{int(organization_id)}_{extension}"


def digest_md5(username: str, password: str, realm: str = ASTERISK_SIP_REALM) -> str:
    """RFC 2617 HA1, the only secret Asterisk needs (``md5_cred``)."""
    return hashlib.md5(f"{username}:{realm}:{password}".encode()).hexdigest()


def new_agent_credentials(organization_id: int, extension: str) -> AgentCredentials:
    username = agent_sip_username(organization_id, extension)
    password = secrets.token_urlsafe(18)
    return AgentCredentials(username, password, digest_md5(username, password))


def sanitize_display_name(name: str) -> str:
    """Strip anything that could break out of a config value or a quoted string."""
    cleaned = _SAFE_TEXT_RE.sub("", name or "").strip()
    return cleaned[:64] or "Agent"


def agent_context(organization_id: int) -> str:
    return f"nimbora-agents-t{int(organization_id)}"


def render_pjsip(agents: Iterable[ContactCenterAgentModel]) -> str:
    lines = [
        "; Generated by NIMBORA Enterprise — do not edit by hand.",
        "; One WebRTC softphone per contact-center agent.",
        "",
    ]
    for agent in agents:
        if not EXTENSION_RE.match(agent.extension):
            logger.warning("Skipping agent {} with invalid extension", agent.id)
            continue
        user = agent_sip_username(agent.organization_id, agent.extension)
        if user != agent.sip_username or not re.fullmatch(
            r"[0-9a-f]{32}", agent.sip_md5_cred
        ):
            logger.warning("Skipping agent {} with inconsistent credentials", agent.id)
            continue
        name = sanitize_display_name(agent.display_name)
        lines += [
            f"[{user}]",
            "type=endpoint",
            # No transport pinned: browsers reach Asterisk's /ws through the
            # TLS reverse proxy, so the socket Asterisk sees is plain ws.
            f"context={agent_context(agent.organization_id)}",
            "disallow=all",
            "allow=opus,ulaw,alaw",
            f"auth={user}",
            f"aors={user}",
            "webrtc=yes",
            "dtls_auto_generate_cert=yes",
            f'callerid="{name}" <{agent.extension}>',
            "device_state_busy_at=1",
            f"set_var=NIMBORA_TENANT={int(agent.organization_id)}",
            "",
            f"[{user}]",
            "type=auth",
            # md5 digest credentials: the clear password is never stored.
            "auth_type=md5",
            f"username={user}",
            f"realm={ASTERISK_SIP_REALM}",
            f"md5_cred={agent.sip_md5_cred}",
            "",
            f"[{user}]",
            "type=aor",
            "max_contacts=3",
            "remove_existing=yes",
            "qualify_frequency=30",
            "",
        ]
    return "\n".join(lines) + "\n"


def render_queues(queues: Iterable[ContactCenterQueueModel]) -> str:
    lines = [
        "; Generated by NIMBORA Enterprise — do not edit by hand.",
        "",
    ]
    for queue in queues:
        strategy = (
            queue.strategy if queue.strategy in ALLOWED_STRATEGIES else "rrmemory"
        )
        lines += [
            f"[{queue_asterisk_name(queue.organization_id, queue.slug)}]",
            f"strategy={strategy}",
            f"timeout={max(5, min(int(queue.ring_timeout_seconds), 120))}",
            "retry=3",
            f"wrapuptime={max(0, min(int(queue.wrapup_seconds), 600))}",
            f"announce-position={'yes' if queue.announce_position else 'no'}",
            "announce-frequency=45",
            "joinempty=yes",
            "leavewhenempty=no",
            "ringinuse=no",
            "musicclass=default",
            "setinterfacevar=yes",
        ]
        for agent in sorted(queue.agents, key=lambda a: a.extension):
            if not agent.is_active or agent.organization_id != queue.organization_id:
                continue
            user = agent_sip_username(agent.organization_id, agent.extension)
            name = sanitize_display_name(agent.display_name).replace(",", " ")
            lines.append(f"member => PJSIP/{user},0,{name},PJSIP/{user}")
        lines.append("")
    return "\n".join(lines) + "\n"


def _overflow_steps(queue: ContactCenterQueueModel) -> list[str]:
    target = (queue.overflow_destination or "").strip()
    if target and EXTENSION_RE.match(target):
        user = agent_sip_username(queue.organization_id, target)
        return [f" same => n,Dial(PJSIP/{user},30)"]
    if target and OVERFLOW_NUMBER_RE.match(target):
        # PSTN overflow goes through the operator-defined outbound context.
        return [f" same => n,Dial(Local/{target}@nimbora-outbound,60)"]
    return []


def render_extensions(
    queues: Iterable[ContactCenterQueueModel],
    agents: Iterable[ContactCenterAgentModel],
) -> str:
    queues = list(queues)
    agents = list(agents)
    lines = [
        "; Generated by NIMBORA Enterprise — do not edit by hand.",
        "",
        f"[{QUEUE_DIALPLAN_CONTEXT}]",
        "; Entry points for AI → human transfers (Local/t<org>-<queue>@nimbora-queues).",
    ]
    for queue in queues:
        name = queue_asterisk_name(queue.organization_id, queue.slug)
        max_wait = max(10, min(int(queue.max_wait_seconds), 3600))
        lines += [
            f"exten => {name},1,NoOp(NIMBORA queue {name})",
            " same => n,Answer()",
            # b(): on each agent leg, attach the AI handoff card id (if any).
            f" same => n,Queue({name},tb({HANDOFF_GOSUB_CONTEXT}^s^1),,,{max_wait})",
            *_overflow_steps(queue),
            " same => n,Hangup()",
        ]
    lines += [
        "",
        f"[{HANDOFF_GOSUB_CONTEXT}]",
        "; Runs on each agent leg before it rings: the softphone reads the",
        "; header and shows the AI agent's handoff card.",
        f'exten => s,1,ExecIf($["${{{HANDOFF_CHANNEL_VARIABLE}}}" != ""]?Set(PJSIP_HEADER(add,{HANDOFF_HEADER})=${{{HANDOFF_CHANNEL_VARIABLE}}}))',
        " same => n,Return()",
        "",
        f"[{CALLBACK_DIALPLAN_CONTEXT}]",
        "; Click-to-call callbacks: reached only by the API's ARI originate,",
        "; once the agent has answered. No endpoint uses this context.",
        "exten => _+X.,1,NoOp(NIMBORA callback ${NIMBORA_CALLBACK})",
        " same => n,Dial(Local/${EXTEN}@nimbora-outbound,60)",
        " same => n,Hangup()",
        "exten => _X.,1,NoOp(NIMBORA callback ${NIMBORA_CALLBACK})",
        " same => n,Dial(Local/${EXTEN}@nimbora-outbound,60)",
        " same => n,Hangup()",
        "",
    ]

    by_org: dict[int, list[ContactCenterAgentModel]] = {}
    for agent in agents:
        if agent.is_active and EXTENSION_RE.match(agent.extension):
            by_org.setdefault(agent.organization_id, []).append(agent)
    for organization_id, org_agents in sorted(by_org.items()):
        lines += [
            f"[{agent_context(organization_id)}]",
            "; Agents may call colleagues of the same company only.",
            "exten => *45,1,PauseQueueMember(,PJSIP/${CHANNEL(endpoint)})",
            " same => n,Playback(beep)",
            " same => n,Hangup()",
            "exten => *46,1,UnpauseQueueMember(,PJSIP/${CHANNEL(endpoint)})",
            " same => n,Playback(beep)",
            " same => n,Hangup()",
        ]
        for agent in sorted(org_agents, key=lambda a: a.extension):
            user = agent_sip_username(organization_id, agent.extension)
            lines += [
                f"exten => {agent.extension},1,Dial(PJSIP/{user},30)",
                " same => n,Hangup()",
            ]
        lines += ["exten => i,1,Hangup()", ""]
    return "\n".join(lines) + "\n"


def _atomic_write(directory: Path, filename: str, content: str) -> bool:
    """Write only when content changed. Returns True when the file changed."""
    directory.mkdir(parents=True, exist_ok=True)
    target = directory / filename
    if target.exists() and target.read_text() == content:
        return False
    fd, tmp = tempfile.mkstemp(dir=directory, prefix=f".{filename}.")
    try:
        with os.fdopen(fd, "w") as handle:
            handle.write(content)
        os.chmod(tmp, 0o644)
        os.replace(tmp, target)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise
    return True


async def _reload_modules(modules: list[str]) -> None:
    if not ASTERISK_ARI_PASSWORD:
        logger.warning("ASTERISK_ARI_PASSWORD not set; skipping Asterisk reload")
        return
    auth = aiohttp.BasicAuth(ASTERISK_ARI_USER, ASTERISK_ARI_PASSWORD)
    timeout = aiohttp.ClientTimeout(total=10)
    async with aiohttp.ClientSession(auth=auth, timeout=timeout) as session:
        for module in modules:
            url = f"{ASTERISK_ARI_URL.rstrip('/')}/asterisk/modules/{module}"
            async with session.put(url) as response:
                if response.status >= 400:
                    body = await response.text()
                    logger.error(
                        "Asterisk reload of {} failed: {} {}",
                        module,
                        response.status,
                        body[:200],
                    )


async def regenerate_asterisk_config(
    *, config_dir: str | None = None, reload: bool = True
) -> dict[str, bool]:
    """Re-render every tenant's queues/agents and reload what changed."""
    if not CONTACT_CENTER_ENABLED and config_dir is None:
        return {}
    from api.db import db_client

    async with _reload_lock:
        queues, agents = await db_client.list_all_active_contact_center_config()
        directory = Path(config_dir or ASTERISK_GENERATED_CONFIG_DIR)
        changed = {
            PJSIP_FILE: _atomic_write(directory, PJSIP_FILE, render_pjsip(agents)),
            QUEUES_FILE: _atomic_write(directory, QUEUES_FILE, render_queues(queues)),
            EXTENSIONS_FILE: _atomic_write(
                directory, EXTENSIONS_FILE, render_extensions(queues, agents)
            ),
        }
        if reload:
            modules = []
            if changed[PJSIP_FILE]:
                modules.append("res_pjsip.so")
            if changed[QUEUES_FILE]:
                modules.append("app_queue.so")
            if changed[EXTENSIONS_FILE]:
                modules.append("pbx_config.so")
            if modules:
                try:
                    await _reload_modules(modules)
                except aiohttp.ClientError as exc:
                    logger.error("Could not reach Asterisk ARI for reload: {}", exc)
        return changed
